"""Generate examples/sample.pdf: a two-page untagged PDF with a heading, paragraphs, a table, and an image."""
import io, sys
from pathlib import Path
from PIL import Image, ImageDraw
from weasyprint import HTML

def _png() -> bytes:
    im = Image.new("RGB", (240, 120), "#dbeafe"); d = ImageDraw.Draw(im)
    d.rectangle((20, 20, 220, 100), outline="#1d4ed8", width=4); d.text((60, 52), "chart placeholder", fill="#1d4ed8")
    buf = io.BytesIO(); im.save(buf, "PNG"); return buf.getvalue()

HTML_SRC = """<html><body style="font-family:Liberation Sans, Arial, sans-serif">
<h1>Sample Report</h1>
<p>This document is generated by scripts/make_sample_pdf.py. It has no structure tags,
no alternative text, and no document language, so ReadReady has work to do.</p>
<h2>Quarterly figures</h2>
<table border="1"><tr><td>Quarter</td><td>Visits</td></tr><tr><td>Q1</td><td>1,204</td></tr><tr><td>Q2</td><td>1,530</td></tr></table>
<img src="data:image/png;base64,{png}">
<p style="page-break-before:always">Second page. A list follows.</p>
<ul><li>First item</li><li>Second item</li></ul>
</body></html>"""

def main(out: Path) -> None:
    import base64
    # WeasyPrint 68.1's HarfBuzz subsetter emits empty 12-byte FontFile2 stubs with the
    # system libharfbuzz-subset, so every viewer renders the text blank; the fontTools path works.
    import weasyprint.pdf.fonts as _wp_fonts
    _wp_fonts.harfbuzz_subset = None
    html = HTML_SRC.format(png=base64.b64encode(_png()).decode())
    out.parent.mkdir(parents=True, exist_ok=True)
    HTML(string=html).write_pdf(out, pdf_tags=False)

if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "examples/sample.pdf"))
