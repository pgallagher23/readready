"""Placeholder alt must not count as a description (G-07).

Run: python -m pytest tests/test_generic_alt_fidelity.py -v
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from audit.auditor import AccessibilityAuditor

TEMPLATE = """<html lang="en"><head><title>T</title></head>
<body><h1>H</h1><img src="a.png" alt="{alt}"></body></html>"""


def _issue_ids(alt):
    # The identifier key is "type".  ("id" is a synthetic sequential value like
    # "issue-10" and would never equal "generic-alt-text".)
    report = AccessibilityAuditor(html_content=TEMPLATE.format(alt=alt)).audit()
    return {i.get("type") for i in report["issues"]}


def test_pipeline_placeholder_is_flagged():
    # The exact string the production incident wrote into every figure.
    assert "generic-alt-text" in _issue_ids("Figure"), (
        "the literal 'Figure' placeholder must be flagged, not accepted"
    )


def test_filename_alt_is_flagged():
    assert "generic-alt-text" in _issue_ids("IMG_1234.png")


def test_office_shape_name_alt_is_flagged():
    """Office shape NAMES are not descriptions.

    Note this is deliberately NOT the Office "Description automatically
    generated" signature: alt_harvest treats that signature as boilerplate to
    TRIM while keeping the description it decorates ("A close up of a sign"),
    so is_generic_alt returns False for it by design.  Asserting otherwise
    would regress harvesting.  The shape name is the generic case.
    """
    assert "generic-alt-text" in _issue_ids("Picture 8")
    assert "generic-alt-text" in _issue_ids("Text Box 9")


def test_real_description_is_accepted():
    assert "generic-alt-text" not in _issue_ids(
        "Example University College of Aviation logo"
    )


def test_office_autogenerated_description_is_kept():
    """The signature is boilerplate; the description it decorates is real."""
    assert "generic-alt-text" not in _issue_ids(
        "A close up of a sign Description automatically generated"
    )
